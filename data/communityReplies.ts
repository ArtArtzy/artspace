const replyAuthors = ["ใบบัว", "เมษ", "RicePaper", "ดาวเหนือ", "มะลิ", "CloudNotes"];

function getReplyBodies(slug: string) {
  return Object.hasOwn(repliesBySlug, slug) ? repliesBySlug[slug] : readingRoomSampleReplies.get(slug) ?? [];
}

export function getCommunityReplyCount(slug: string) {
  return getReplyBodies(slug).reduce((count, seed) => count + (typeof seed === "string" ? 1 : 2), 0);
}

export function getCommunityReplies(slug: string) {
  const firstAuthor = Array.from(slug).reduce((total, character) => total + character.charCodeAt(0), 0);
  const comments = getReplyBodies(slug);

  return comments.map((seed, index) => {
    const id = `comment-${index + 1}`;
    return {
      id,
      author: replyAuthors[(firstAuthor + index) % replyAuthors.length],
      body: typeof seed === "string" ? seed : seed.body,
      reply: typeof seed === "string" ? undefined : {
        id: `${id}-reply-1`,
        author: replyAuthors[(firstAuthor + comments.length + index) % replyAuthors.length],
        body: seed.reply,
      },
    };
  });
}
