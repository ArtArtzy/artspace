const roomAuthors: Record<CommunityRoom, ThreadAuthor> = {
  general: "ink",
  novel: "moonlight",
  fanfic: "purplemoon",
  cartoon: "kuroi",
};

export function getNewRoomThreads(room: CommunityRoom): FeedPost[] {
  const samples = room === "general" ? [] : readingRoomSamples[room].map(({ replies, ...thread }) => thread);
  return [...threadSeeds[room], ...samples].map(({ author = roomAuthors[room], age = "วันนี้", ...thread }) => ({
    ...thread,
    ...threadAuthors[author],
    badge: communityRooms[room].label,
    badgeClass: "border border-arn-accent/35 bg-arn-surface text-arn-accent-soft",
    age,
    likes: "0",
  }));
}

export function communitySectionHref(section: CommunityRoom | "events") {
  return section === "general" ? "/community" : `/community?section=${section}`;
}

export function communityCreateHref(room: CommunityRoom) {
  return `/community/create-post?room=${room}`;
}

export function isLocalCommunityThread(slug: string) {
  return /^local-[0-9a-f]{32}$/.test(slug);
}
